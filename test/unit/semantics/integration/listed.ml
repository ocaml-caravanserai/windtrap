(* [incr] and [decr] under a local open of each module of the fixed list.
   Each one is a site, and its arm compiles. Of these modules only [Atomic]
   gives the two counters. *)

let int_incr r = Int.(incr r)
let int_decr r = Int.(decr r)
let float_incr r = Float.(incr r)
let float_decr r = Float.(decr r)
let int32_incr r = Int32.(incr r)
let int32_decr r = Int32.(decr r)
let int64_incr r = Int64.(incr r)
let int64_decr r = Int64.(decr r)
let nativeint_incr r = Nativeint.(incr r)
let nativeint_decr r = Nativeint.(decr r)
let char_incr r = Char.(incr r)
let char_decr r = Char.(decr r)
let string_incr r = String.(incr r)
let string_decr r = String.(decr r)
let bytes_incr r = Bytes.(incr r)
let bytes_decr r = Bytes.(decr r)
let list_incr r = List.(incr r)
let list_decr r = List.(decr r)
let array_incr r = Array.(incr r)
let array_decr r = Array.(decr r)
let option_incr r = Option.(incr r)
let option_decr r = Option.(decr r)
let result_incr r = Result.(incr r)
let result_decr r = Result.(decr r)
let bool_incr r = Bool.(incr r)
let bool_decr r = Bool.(decr r)
let fun_incr r = Fun.(incr r)
let fun_decr r = Fun.(decr r)
let seq_incr r = Seq.(incr r)
let seq_decr r = Seq.(decr r)
let hashtbl_incr r = Hashtbl.(incr r)
let hashtbl_decr r = Hashtbl.(decr r)
